export function copy(locale: string): Copy {
  return locale === "zh" ? zh : locale === "es" ? es : en;
}
export const errorText = (t: Copy, code: string) =>
  code in t ? t[code as keyof Copy] : t.genericError;
export function stateLabel(locale: string, state: string) {
  if (state === "processing")
    return locale === "zh"
      ? "处理中"
      : locale === "es"
        ? "En curso"
        : "In progress";
  if (state === "failed")
    return locale === "zh"
      ? "需要处理"
      : locale === "es"
        ? "Necesita atención"
        : "Needs attention";
  const t = copy(locale);
  return t[state as keyof Copy] || state;
}
